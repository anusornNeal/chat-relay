import assert from "node:assert/strict";
import { LearnGateCache, preflightIdentity, preflightScope, preflightPreparationScopes, isPreflightExempt, preflightRequired } from "../src/learn-preflight-gate.mjs";
const h = (items={}) => new Headers(items);
assert.equal(preflightIdentity({"openai/session":"chat-1"},h({"mcp-session-id":"transport"})).reliable,true);
assert.notEqual(preflightIdentity({"openai/session":"chat-1"},h()).source,preflightIdentity({"openai/session":"chat-2"},h()).source);
assert.equal(preflightIdentity(null,h({"mcp-session-id":"transport"})).reliable,false);
assert.equal(preflightIdentity(null,h({})).source,undefined);
assert.equal(preflightScope({cwd:"C:\\Users\\owner\\Projects\\Flowly\\src"}),"project:flowly");
assert.equal(preflightScope({projectKey:"CHAT-RELAY"}),"project:chat-relay");
assert.equal(preflightScope({path:"/tmp/other"}),"global");
assert.deepEqual(preflightPreparationScopes({cwd:"C:\\Users\\owner\\Projects\\Flowly"}, "flowly"),["global","project:flowly"]);
assert.equal(isPreflightExempt("learn_prepare"),true);
assert.equal(isPreflightExempt("terminal_exec"),false);
assert.equal(preflightRequired("terminal_exec","global").code,"LEARN_PREPARE_REQUIRED");
let now=1000;
const cache = new LearnGateCache({now:()=>now, maxEntries:3});
assert.equal(cache.blockedOrFallback("a","chat1","global"),true);
assert.equal(cache.blockedOrFallback("a","chat1","global"),true);
assert.equal(cache.blockedOrFallback("a","chat1","global"),true);
assert.equal(cache.blockedOrFallback("a","chat1","global"),true);
assert.equal(cache.get("a","chat1","global").blocks,2);
assert.equal(cache.get("a","chat1","global").bypass,undefined);
cache.markPrepared("a","chat1",["global"]);
assert.equal(cache.blockedOrFallback("a","chat1","global"),false);
cache.bypass("c","chat1","global");
assert.equal(cache.blockedOrFallback("c","chat1","global"),false);
assert.equal(cache.get("b","chat1","global"),null);
cache.markPrepared("b","chat1",["global","project:flowly"]);
assert.equal(cache.get("b","chat1","project:flowly").prepared,true);
assert.equal(cache.get("b","chat2","global"),null);
now+=5*60*1000+1;
assert.equal(cache.get("a","chat1","global"),null);
